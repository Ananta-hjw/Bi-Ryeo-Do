        public static string[] Outcome(StoryChoiceEvent ev, int choice)
        {
            if (ev == null || choice < 0 || choice >= ev.Choices.Length)
                throw new System.ArgumentOutOfRangeException(nameof(choice));
            return ev.Choices[choice].Outcome;
        }
