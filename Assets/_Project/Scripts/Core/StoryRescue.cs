        public static string ActorName(string id)
        {
            switch (id)
            {
                case "story_biry_rescue": return "비류연";
                case "story_hyeon_un": return "현운";
                case "story_namgung_sansan": return "남궁산산";
                case "story_ok_yugyeong": return "옥유경";
                case "story_baek_muyeong": return "백무영";
                case "story_dangsam": return "당삼";
                default: return null;
            }
        }
        public static string ArtKey(string id) { return id == "story_biry_rescue" ? "player" : id == "story_dangsam" ? "dang_cheolyeong" : null; }
        private static SkillSpec Hit(string id, string name, float power, int hits = 1)
        {
            return new SkillSpec { Id = id, Name = name, Description = "이 공방에서 사용하는 이야기 전용 기술입니다.", Power = power, Hits = hits, QiCost = 16, Cooldown = 1, Range = 3 };
        }
        private static SkillSpec Avoid(string id, string name)
        {
            return new SkillSpec { Id = id, Name = name, Description = "흐름을 읽고 이 장면의 목표에 대응합니다.", Power = 0, Effect = SkillEffect.Evade, QiCost = 0, Cooldown = 0 };
        }
        public static void PrepareParty(StageData stage, int encounter, IEnumerable<Combatant> party)
        {
            if (stage == null || stage.IsQuest || stage.IsTower || stage.Number < 49 || stage.Number > 57) return;
            foreach (var member in party)
            {
                List<SkillSpec> skills = null;
                switch (member.Id)
                {
                    case "story_biry_rescue": skills = new List<SkillSpec> { Hit("scene_rescue_fist", "삼복구타권법 중복", 2.5f, 2), Avoid("scene_rescue_step", "봉황무") }; break;
                    case "story_mo_yonghwi": skills = new List<SkillSpec> { Hit("scene_star_sword", "은하일섬", 4f, 1), Hit("scene_star_rain", "은하유성만천", 3f, 2), Avoid("scene_star_step", "유성보") }; break;
                    case "story_gongson_jeolhwi": skills = new List<SkillSpec> { Hit("scene_gongson_sword", "지존검", 3f, 2), Avoid("scene_gongson_step", "지존군림보") }; break;
                    case "story_hyeon_un": skills = new List<SkillSpec> { Hit("scene_taicheong", "태청강기사 청천우", 3f, 2), Avoid("scene_tao_step", "제운종") }; break;
                    case "story_namgung_sansan": skills = new List<SkillSpec> { Hit("scene_thunder_scar", "뇌전참흔", 3f, 2), Hit("scene_thunder_shadow", "뇌광참영", 6f, 1), Avoid("scene_sansan_step", "전뢰보") }; break;
                    case "story_ok_yugyeong": skills = new List<SkillSpec> { Hit("scene_blood_blade", "혈풍란", 3f, 2), Avoid("scene_ok_step", "추격의 틈") }; break;
                    case "story_namgung_sang": skills = new List<SkillSpec> { Hit("scene_injured_sword", "뇌광단천", 3f, 2), Avoid("scene_namgung_step", "퇴로를 살핀다") }; break;
                    case "story_dangsam": skills = new List<SkillSpec> { Hit("scene_dang_darts", "당문 암기", 2f, 3), Avoid("scene_dang_smoke", "안락휴 준비") }; break;
                    case "story_baek_muyeong": skills = new List<SkillSpec> { Hit("scene_baek_sword", "형산의 검", 3f, 2), Avoid("scene_baek_step", "바람 읽기") }; break;
                }
                if (stage.Number == 49 && encounter == 1 && member.Id == "story_biry_rescue")
                {
                    skills.Add(Hit("scene_air_push", "격공장", 0.3f, 1));
                }
                if (stage.Number == 49 && encounter == 2 && member.Id == "story_biry_rescue")
                {
                    skills = new List<SkillSpec> { Avoid("scene_safe_27", "27번 · 왼쪽 안전칸"), Avoid("scene_fall_37", "37번 · 가운데 낙하칸"), Avoid("scene_fall_47", "47번 · 오른쪽 낙하칸") };
                }
                if (stage.Number == 49 && encounter == 3 && member.Id == "story_biry_rescue")
                {
                    skills.Add(Hit("scene_needle_flash", "뇌섬일시", 6f, 1));
                }
                if (stage.Number == 49 && encounter == 4 && member.Id == "story_biry_rescue")
                {
                    skills.Add(Avoid("scene_rain_step", "우중거 불점의"));
                }
                if (stage.Number == 49 && encounter == 5 && member.Id == "story_biry_rescue")
                {
                    skills.Add(Avoid("scene_mind_wave", "심뢰열파"));
                }
                if (stage.Number == 49 && encounter == 6 && member.Id == "story_biry_rescue")
                {
                    skills.Add(Hit("scene_eight_shadows", "팔섬 뇌광굉타", 0.6f, 8));
                }
                if (stage.Number == 50 && encounter == 2 && member.Id == "story_mo_yonghwi")
                {
                    skills.Add(Avoid("scene_sense_heat", "눈을 감고 열기를 읽는다"));
                }
                if (stage.Number == 50 && encounter == 3 && member.Id == "story_mo_yonghwi")
                {
                    skills.Add(Hit("scene_ice_union", "염천빙지 일원합", 7f, 1));
