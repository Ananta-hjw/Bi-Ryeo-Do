        public static string ActorName(string id)
        {
            switch (id)
            {
                case "story_biry_staff": case "story_biry_search": case "story_biry_half": return "비류연";
                case "story_yeonbi_left": return "연비";
                case "story_ryu_eungyeong": return "류은경";
                case "story_yong_cheongmyeong": return "용천명";
                default: return null;
            }
        }

        public static string ArtKey(string id)
        {
            switch (id)
            {
                case "story_biry_staff": case "story_biry_search": case "story_biry_half": return "player";
                case "story_yeonbi_left": return "yeonbi";
                case "story_yong_cheongmyeong": return "yong_cheonmyeong";
                default: return null;
            }
        }

        private static SkillSpec Hit(string id, string name, float power, int hits = 1)
        {
            return new SkillSpec { Id = id, Name = name, Description = "이 공방에서 사용하는 이야기 전용 기술입니다.", Power = power, Hits = hits, QiCost = 18, Cooldown = 1, Range = 3 };
        }
        private static SkillSpec Avoid(string id, string name)
        {
            return new SkillSpec { Id = id, Name = name, Description = "공세를 읽고 대응합니다.", Power = 0, Effect = SkillEffect.Evade, QiCost = 12, Cooldown = 1 };
        }

        /// <summary>Change scene commands without changing wounds, gauges or the saved equipment/arts.</summary>
        public static void PrepareParty(StageData stage, int encounter, IEnumerable<Combatant> party)
        {
            if (stage == null || stage.IsQuest || stage.IsTower || stage.Number < 42 || stage.Number > 48) return;
            foreach (var member in party)
            {
                List<SkillSpec> skills = null;
                switch (member.Id)
                {
                    case "story_biry_staff":
                        skills = new List<SkillSpec> { Hit("scene_staff", "삼복구타봉법", 2.5f, 2), Avoid("scene_shell_deflect", "벽력포 흘리기"), Hit("scene_shell_cut", "벽력탄 가르기", 6f), Hit("scene_muzzle_stop", "포구 막기", 4f) }; break;
                    case "story_yeonbi_left":
                        if (stage.Number == 46 && encounter == 3)   // the 천외일도 showdown: 묵뢰살 comes from its icon, not a command
                            skills = new List<SkillSpec> { Hit("scene_left_umbrella", "현천은린 회천", 2.6f, 2), Avoid("scene_left_evade", "검로 읽기") };
                        else skills = new List<SkillSpec> { Hit("scene_left_umbrella", "현천은린 회천", 2.6f, 2), Avoid("scene_left_evade", "왼손 우산막"), Avoid("scene_redirect", "기류를 땅으로 돌린다"), Hit("scene_umbrella_spear", "천지무견 자다봉창", 6f) };
                        break;
                    case "story_ryu_eungyeong":
                        skills = new List<SkillSpec> { Avoid("scene_suyak", "수약답운"), Hit("scene_seonpung", "선풍검계", 6f), Hit("scene_wind_sword", "풍령검", 2.4f, 2) }; break;
                    case "story_yong_cheongmyeong":
                        skills = new List<SkillSpec> { Hit("scene_geumgang", "금강복마지", 7f), Avoid("scene_budong", "부동명왕보"), Hit("scene_tanji", "탄지신통", 3f) }; break;
                    case "story_namgung_sang":
                        skills = new List<SkillSpec> { Hit("scene_roegwang", "뇌광단천", 4f, 2), Avoid("scene_roegwang_step", "뇌광산란") }; break;
                    case "story_biry_search":
                        skills = new List<SkillSpec> { Hit("scene_search_fist", "삼복구타권법", 2.4f, 2), Avoid("scene_confirm_charm", "남겨진 뿔 장식 확인"), Avoid("scene_search_step", "퇴로 살피기") }; break;
                    case "story_biry_half":
                        skills = new List<SkillSpec> { Hit("scene_loaned_darts", "빌린 비뢰도", 1f, 5), Hit("scene_jungbok", "삼복구타권법 중복", 2.5f, 2), Avoid("scene_half_step", "봉황무의 틈") };
                        break;
                    case "na_yerin":
                        if (stage.Number == 45 && encounter > 0)
                        {
                            var form = encounter == 1 ? Hit("scene_soan", "소안검", 3f) : encounter == 2 ? Hit("scene_hanbing", "한빙섬옥", 4f, 2) : Hit("scene_haesang", "해상비조천참절", 8f);
                            skills = new List<SkillSpec> { form, Avoid("scene_ny_step", "비설보") };
                        }
                        break;
                    case "yun_junho":
                        if (stage.Number == 44 && encounter == 2)
                        {
                            member.Name = "윤미";
                            member.StoryArtId = "yunmi";
                            skills = new List<SkillSpec> { Hit("scene_chilmae", "칠매검", 3.6f, 2), Avoid("scene_yunmi_step", "매화의 보법") };
                        }
                        break;
                    case "jang_hong":
                        member.Skills.RemoveAll(skill => skill.Id == "scene_trace");
                        break;
                }
                if (skills == null) continue;
                member.Skills.RemoveAll(skill => skill.Id != "basic");
                member.Skills.AddRange(skills);
            }
        }

